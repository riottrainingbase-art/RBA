#!/usr/bin/env node
// Draft-only generator. Never creates payment links, sends mail or publishes an event.
import fs from "node:fs";
import path from "node:path";
const root=process.cwd();
const file=path.join(root,"components/clinic-auto-generated.ts");
const input=process.env.CLINIC_EVENT_JSON||"";
const bad=(s)=>/undefined|null|\{\{|\}\}|<script|javascript:/i.test(s);
const slugPattern=/^[a-z0-9]+(?:-[a-z0-9]+)*$/;
function check(v){
 if(!v||typeof v!=="object"||Array.isArray(v))throw Error("Event must be a JSON object");
 const required=["slug","area","title","date","venue","audience","intro"];
 for(const key of required)if(typeof v[key]!=="string"||!v[key].trim()||bad(v[key]))throw Error("Invalid field: "+key);
 if(!slugPattern.test(v.slug)||v.slug.length>90)throw Error("Invalid slug");
 if(v.area.length>32||v.title.length>140||v.date.length>100||v.venue.length>150||v.audience.length>140||v.intro.length>600)throw Error("Field too long");
 if(!/^\d{4}-\d{2}-\d{2}$/.test(v.eventDate)||Number.isNaN(Date.parse(v.eventDate+"T00:00:00Z")))throw Error("eventDate must be YYYY-MM-DD");
 if(v.status&&v.status!=="planning")throw Error("Generator only creates planning drafts");
 if(v.registrationUrl||v.paymentUrl||v.priceId||v.checkoutUrl)throw Error("Payment/registration fields prohibited in draft generation");
 if(v.venueConfirmed!==true)throw Error("Venue confirmation evidence required");
 if(typeof v.venueEvidenceUrl!=="string"||!/^https:\/\//.test(v.venueEvidenceUrl)||bad(v.venueEvidenceUrl))throw Error("Evidence URL required");
 if(!["https://","http://"].some(x=>v.venueEvidenceUrl.startsWith(x)))throw Error("Invalid evidence URL");
 return {slug:v.slug,area:v.area.toUpperCase(),title:v.title,date:v.date,venue:v.venue,audience:v.audience,fee:"未確定",status:"planning",intro:v.intro,focus:["技術を実戦へ","相手を見て判断","ゲームで試す"],note:"開催地・日程の確認資料を保管済み。料金・定員・参加条件・申込・決済は別途確認し、公開承認後に案内します。"};
}
function run(){
 const data=JSON.parse(input);const event=check(data);
 const previous=fs.existsSync(file)?fs.readFileSync(file,"utf8"):"";
 const match=previous.match(/export const generatedClinicPages: Event\[\] = (\[[\s\S]*?\]);/);
 if(!match)throw Error("Generated file has unexpected format; manual review required");
 const existing=JSON.parse(match[1]);
 if(existing.some(e=>e.slug===event.slug))throw Error("Duplicate generated slug");
 const core=fs.readFileSync(path.join(root,"components/clinic-pages-data.ts"),"utf8");
 if(core.includes('slug:"'+event.slug+'"')||core.includes('slug: "'+event.slug+'"'))throw Error("Slug already exists in core registry");
 existing.push(event);
 fs.writeFileSync(file,'// Generated by scripts/create-clinic-draft.mjs. Do not edit by hand.\nimport type { Event } from "./clinic-pages-data";\nexport const generatedClinicPages: Event[] = '+JSON.stringify(existing,null,2)+';\n');
 console.log(JSON.stringify({created:event.slug,status:"planning",paymentEnabled:false,publication:"PR review only",evidence:data.venueEvidenceUrl}));
}
if(process.argv.includes("--self-test")){
 const valid={slug:"sample-2027",area:"MIYAGI",title:"サンプル",date:"2027年1月1日",venue:"サンプル体育館",audience:"U12",intro:"サンプルです",eventDate:"2027-01-01",venueConfirmed:true,venueEvidenceUrl:"https://example.org/booking"};
 check(valid);
 for(const badCase of [{...valid,venueConfirmed:false},{...valid,paymentUrl:"https://example.org/pay"},{...valid,slug:"../../unsafe"},{...valid,intro:"undefined"}]){let failed=false;try{check(badCase)}catch{failed=true}if(!failed)throw Error("Invalid case was accepted")}
 console.log("Clinic draft validation tests passed");
}else run();
